export const DEFAULT_LOCALE: LocaleCode = 'en';

export const isSupported = (code: string): code is LocaleCode =>
  LOCALES.some((locale) => locale.code === code);

/** Falls back to English so a missing translation never renders as a raw key. */
export const translate = (code: string, key: string): string =>
  STRINGS[code]?.[key] ?? STRINGS[DEFAULT_LOCALE][key] ?? key;

/** The launch parameter for the game client; English for anything unknown. */
export const gameLanguage = (code: string) => (isSupported(code) ? code : DEFAULT_LOCALE);
